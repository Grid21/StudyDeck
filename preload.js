'use strict';
const { contextBridge, ipcRenderer, webUtils } = require('electron');
const call = (name) => (...a) => ipcRenderer.invoke(name, ...a);

contextBridge.exposeInMainWorld('studydeck', {
  info: call('app:info'),
  restart: call('app:restart'),
  openDataFolder: call('app:openDataFolder'),
  listPlugins: call('plugins:list'),
  openPluginsFolder: call('plugins:openFolder'),
  listDecks: call('decks:list'),
  importDecks: call('decks:import'),
  deleteDeck: call('decks:delete'),
  createDeck: call('decks:create'), renameDeck: call('decks:rename'),
  addNote: call('notes:add'), listNotes: call('notes:list'), getNote: call('notes:get'), updateNote: call('notes:update'), deleteNote: call('notes:delete'),
  restartWhenSynced: call('app:restartWhenSynced'), isSyncing: call('app:syncing'),
  onUpdateInstalled: (cb) => ipcRenderer.on('updates:installed', (_e, r) => cb(r)),
  studyNext: call('study:next'),
  studyAnswer: call('study:answer'),
  progress: call('progress:get'),
  getSettings: call('settings:get'),
  setSettings: call('settings:set'),
  chooseUpdate: call('updates:choose'),
  installUpdate: call('updates:install'),
  removeUpdates: call('updates:remove'),
  checkUpdate: call('updates:check'),
  downloadInstallUpdate: call('updates:downloadInstall'),
  getUpdatePrefs: call('updates:getPrefs'),
  setUpdatePrefs: call('updates:setPrefs'),
  friendsState: call('friends:state'),
  friendsSetServer: call('friends:setServer'),
  friendsRegister: call('friends:register'),
  friendsLogin: call('friends:login'),
  friendsLogout: call('friends:logout'),
  friendsList: call('friends:list'),
  friendsRequest: call('friends:request'),
  friendsRespond: call('friends:respond'),
  friendsRemove: call('friends:remove'),
  friendsSetShares: call('friends:setShares'),
  friendsSync: call('friends:sync'),
  friendsCompare: call('friends:compare'),
  friendsSubjects: call('friends:subjects'),
  friendsDeleteAccount: call('friends:deleteAccount'),
  ankiState: call('anki:state'),
  ankiLogin: call('anki:login'),
  ankiLogout: call('anki:logout'),
  ankiSync: call('anki:sync'),
  onAnkiProgress: (cb) => ipcRenderer.on('anki:progress', (_e, m) => cb(String(m))),
  friendsDiscordConfig: call('friends:discordConfig'),
  friendsDiscordBegin: call('friends:discordBegin'),
  friendsDiscordPoll: call('friends:discordPoll'),
  friendsSetDiscoverable: call('friends:setDiscoverable'),
  friendsSuggestions: call('friends:suggestions'),
  pathForFile: (file) => { try { return webUtils.getPathForFile(file); } catch { return ''; } }
});
